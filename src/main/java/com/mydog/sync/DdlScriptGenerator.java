package com.mydog.sync;

import com.mydog.util.SqlNames;
import com.mydog.util.ValueFormatter;

import java.io.BufferedWriter;
import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Renders a {@link SyncPlan} as a script that can be reviewed and run by hand, without MyDog.
 *
 * <p>Export re-runs the data diff while writing rather than replaying a buffered list: a plan for a
 * large schema can describe millions of row changes, and the point of the file is that a person can
 * open it. Rows are streamed to the writer, so the export costs time but not heap.
 *
 * <p>The script mirrors what {@link SyncExecutor} would do — foreign key checks off, structure
 * before data, triggers last — so running it by hand and pressing Execute produce the same result.
 */
public final class DdlScriptGenerator {

    /** Rows per generated INSERT statement. Multi-row VALUES keeps the file small and reviewable. */
    private static final int INSERT_BATCH = 100;

    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    private DdlScriptGenerator() {
    }

    public static String generate(SyncPlan plan, SyncOptions options) throws Exception {
        StringBuilder out = new StringBuilder(16 * 1024);
        writeTo(plan, options, out);
        return out.toString();
    }

    /** Streams the script for the selected actions into {@code out}. */
    public static void writeTo(SyncPlan plan, SyncOptions options, Appendable out) throws Exception {
        List<SyncAction> actions = plan.selectedActions();
        line(out, "-- MyDog synchronization script");
        line(out, "-- source: " + plan.sourceLabel() + "    target: " + plan.targetLabel());
        line(out, "-- mode: " + options.mode() + (options.dropExtraneous() ? " (+ drop extraneous)" : "")
                + (options.fastDataMode() ? " (+ fast data mode)" : ""));
        line(out, "-- generated: " + LocalDateTime.now().format(STAMP));
        line(out, "-- generated by re-reading both servers; row data below reflects that moment.");
        out.append('\n');

        String schema = actions.isEmpty() ? null : actions.get(0).object().schema();
        if (schema != null) {
            line(out, "USE " + SqlNames.quote(schema) + ";");
        }
        line(out, "SET NAMES utf8mb4;");
        line(out, "SET FOREIGN_KEY_CHECKS = 0;");
        out.append('\n');

        for (ObjectKind kind : ObjectKind.values()) {
            boolean headerWritten = false;
            for (SyncAction action : actions) {
                if (action.object().kind() != kind) continue;
                if (!headerWritten) {
                    line(out, "-- ============================================================ "
                            + kind.name().toLowerCase(java.util.Locale.ROOT));
                    headerWritten = true;
                }
                writeAction(out, action, kind);
            }
        }

        line(out, "SET FOREIGN_KEY_CHECKS = 1;");
        line(out, "-- end of script");
    }

    /** Writes the script straight to a file (UTF-8), streaming row by row. */
    public static void exportTo(SyncPlan plan, SyncOptions options, Path file) throws Exception {
        Path parent = file.toAbsolutePath().getParent();
        if (parent != null) Files.createDirectories(parent);
        try (Writer writer = new BufferedWriter(Files.newBufferedWriter(file, StandardCharsets.UTF_8), 1 << 16)) {
            writeTo(plan, options, writer);
        }
    }

    // ------------------------------------------------------------------ one action

    private static void writeAction(Appendable out, SyncAction action, ObjectKind kind) throws Exception {
        line(out, "-- " + action.kind() + " " + action.object().qualified()
                + (action.detail() == null || action.detail().isEmpty() ? "" : "  (" + action.detail() + ")"));
        // routine and trigger bodies contain their own semicolons, so the client delimiter changes
        boolean bodyKind = kind == ObjectKind.PROCEDURE || kind == ObjectKind.FUNCTION
                || kind == ObjectKind.TRIGGER;
        for (String sql : action.statements()) {
            String statement = sql.strip();
            if (!statement.endsWith(";")) statement = statement + ";";
            if (bodyKind || hasInnerSemicolon(statement)) {
                // body contains statement terminators: the mysql client needs its own delimiter
                line(out, "DELIMITER $$");
                line(out, statement.substring(0, statement.length() - 1) + " $$");
                line(out, "DELIMITER ;");
            } else {
                line(out, statement);
            }
        }
        if (action.hasData()) {
            out.append('\n');
            line(out, "-- data: " + (action.upsert() ? "upsert of every source row" : "row-by-row diff"));
            TextSink sink = new TextSink(out, action.object());
            action.dataProducer().produce(sink);
            sink.finish();
            out.append('\n');
        } else if (!action.statements().isEmpty()) {
            out.append('\n');
        }
    }

    // ------------------------------------------------------------------ rows as text

    /** Turns streamed row changes into INSERT / UPDATE / DELETE statements. */
    private static final class TextSink implements DataProducer.ChangeSink {

        private final Appendable out;
        private final ObjectRef object;
        private List<String> batchColumns;
        private int batched;

        TextSink(Appendable out, ObjectRef object) {
            this.out = out;
            this.object = object;
        }

        @Override
        public void insert(Row row) throws Exception {
            List<String> columns = row.columns();
            if (batched > 0 && columns.equals(batchColumns)) {
                out.append(",\n  (").append(values(columns, row)).append(')');
                if (++batched >= INSERT_BATCH) endInsert();
                return;
            }
            endInsert();
            batchColumns = columns;
            out.append("INSERT INTO ").append(tableRef()).append(" (")
                    .append(SqlNames.columnList(columns)).append(")\nVALUES\n  (")
                    .append(values(columns, row)).append(')');
            batched = 1;
        }

        @Override
        public void update(Row sourceRow, Row targetRow) throws Exception {
            endInsert();
            List<String> keys = sourceRow.keyColumns();
            StringBuilder sql = new StringBuilder("UPDATE ").append(tableRef()).append(" SET ");
            boolean first = true;
            for (String column : sourceRow.columns()) {
                if (keys.contains(column)) continue;
                if (!containsIgnoreCase(targetRow.columns(), column)) continue;
                if (!first) sql.append(", ");
                sql.append(SqlNames.quote(column)).append(" = ")
                        .append(ValueFormatter.sqlLiteral(sourceRow.value(column)));
                first = false;
            }
            if (first) return;   // nothing but keys changed; nothing to write
            sql.append(" WHERE ").append(predicate(keys, sourceRow));
            line(out, sql.append(';').toString());
        }

        @Override
        public void delete(Row targetRow) throws Exception {
            endInsert();
            List<String> keys = targetRow.keyColumns();
            if (keys.isEmpty()) return;   // cannot address this row safely; execution path warns too
            line(out, "DELETE FROM " + tableRef() + " WHERE " + predicate(keys, targetRow) + ";");
        }

        /** Flushes an open multi-row INSERT. Callers must invoke this before any other statement. */
        void finish() throws Exception {
            endInsert();
        }

        private void endInsert() throws Exception {
            if (batched == 0) return;
            line(out, ";");
            batched = 0;
            batchColumns = null;
        }

        private String tableRef() {
            return SqlNames.qualified(object.schema(), object.name());
        }

        private static String values(List<String> columns, Row row) {
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < columns.size(); i++) {
                if (i > 0) sb.append(", ");
                sb.append(ValueFormatter.sqlLiteral(row.value(columns.get(i))));
            }
            return sb.toString();
        }

        private static String predicate(List<String> keys, Row row) {
            StringBuilder sb = new StringBuilder();
            for (int i = 0; i < keys.size(); i++) {
                if (i > 0) sb.append(" AND ");
                String key = keys.get(i);
                Object value = row.value(key);
                sb.append(SqlNames.quote(key))
                        .append(value == null ? " IS NULL" : " = " + ValueFormatter.sqlLiteral(value));
            }
            return sb.toString();
        }
    }

    /** True when the statement carries a terminator before its own final one. */
    private static boolean hasInnerSemicolon(String statement) {
        return statement.indexOf(';') < statement.length() - 1;
    }

    private static boolean containsIgnoreCase(List<String> list, String value) {
        for (String s : list) {
            if (s.equalsIgnoreCase(value)) return true;
        }
        return false;
    }

    private static void line(Appendable out, String text) throws IOException {
        out.append(text).append('\n');
    }
}
